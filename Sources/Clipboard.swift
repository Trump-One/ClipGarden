import AppKit

final class ClipboardReader {
    static let ownType = NSPasteboard.PasteboardType("local.clipgarden.own-copy")
    static let skippedTypes = ["org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword", "com.typeit4me.clipping"]
    static let maxTextBytes = 2 * 1024 * 1024
    static let maxImageBytes = 20 * 1024 * 1024
    var lastChange: Int = -1
    var ownChange: Int?
    func baseline(_ pasteboard: NSPasteboard) { lastChange = pasteboard.changeCount }
    func readChange(_ pasteboard: NSPasteboard) -> ClipPayload? {
        let change = pasteboard.changeCount
        guard change != lastChange else { return nil }; lastChange = change
        if change == ownChange { ownChange = nil; return nil }
        ownChange = nil
        let types = pasteboard.types ?? []
        if types.contains(where: { type in Self.skippedTypes.contains(type.rawValue) || type.rawValue.lowercased().contains("password") || type.rawValue.lowercased().contains("concealed") }) { return nil }
        if types.contains(.fileURL) { return nil }
        if types.contains(.png) || types.contains(.tiff) {
            // Inspect only typed image bytes; never follow file URLs.
            let raw = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff)
            guard let raw, raw.count <= Self.maxImageBytes, let rep = NSBitmapImageRep(data: raw), rep.pixelsWide > 0, rep.pixelsHigh > 0, rep.pixelsWide <= 12_000, rep.pixelsHigh <= 12_000, Int64(rep.pixelsWide) * Int64(rep.pixelsHigh) <= 30_000_000, let image = NSImage(data: raw), let payload = ClipPayload.image(image), payload.data.count <= Self.maxImageBytes else { return nil }
            return payload
        }
        guard let text = pasteboard.string(forType: .string), !text.isEmpty, text.utf8.count <= Self.maxTextBytes else { return nil }
        return .text(text)
    }
    @discardableResult func write(_ value: ClipPayload, to pasteboard: NSPasteboard) -> Bool {
        let item = NSPasteboardItem()
        item.setString(UUID().uuidString, forType: Self.ownType)
        if value.kind == .text { item.setString(value.text, forType: .string) }
        else { item.setData(value.data, forType: .png) }
        pasteboard.clearContents()
        let success = pasteboard.writeObjects([item])
        if success { ownChange = pasteboard.changeCount }
        return success
    }
}
